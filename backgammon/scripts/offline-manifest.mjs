import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";
const base = new URL("..", import.meta.url).pathname;
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory()
      ? [
          "tests",
          "test-results",
          "scripts",
          "docs",
          "source",
          "node_modules",
          "refresh",
        ].includes(e.name)
        ? []
        : walk(join(dir, e.name))
      : [join(dir, e.name)],
  );
}
const files = walk(base).filter(
  (p) =>
    !p.endsWith(".md") &&
    !p.endsWith("offline-manifest.js") &&
    !p.endsWith("sw.js") &&
    !p.endsWith("package.json"),
);
const heavy = files.filter((p) => p.includes("/engine/vendor/")),
  shell = files.filter((p) => !heavy.includes(p));
const hash = createHash("sha256");
hash.update(readFileSync(join(base, "sw.js")));
for (const p of files.sort())
  hash.update(relative(base, p)).update(readFileSync(p));
for (const shared of ["hub.css", "hub.js", "peer-room.js"]) {
  hash.update(shared).update(readFileSync(join(base, "..", "shared", shared)));
}
const url = (p) => "/backgammon/" + relative(base, p);
const engineDigests = Object.fromEntries(
  heavy.map((p) => [
    url(p),
    createHash("sha256").update(readFileSync(p)).digest("hex"),
  ]),
);
writeFileSync(
  join(base, "offline-manifest.js"),
  `// Generated by scripts/offline-manifest.mjs\nself.BG_CACHE_VERSION='${hash.digest("hex").slice(0, 16)}';\nself.BG_SHELL=${JSON.stringify([...shell.map(url), "/shared/hub.css", "/shared/hub.js", "/shared/peer-room.js"])};\nself.BG_ENGINE=${JSON.stringify(heavy.map(url))};\nself.BG_ENGINE_DIGESTS=${JSON.stringify(engineDigests)};\n`,
);
