import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";
const base = new URL("..", import.meta.url).pathname;
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => !e.name.startsWith("."))
    .flatMap((e) =>
      e.isDirectory()
        ? [
            "tests",
            "test-results",
            "scripts",
            "docs",
            "source",
            "node_modules",
            "refresh",
          ].includes(e.name)
          ? []
          : walk(join(dir, e.name))
        : [join(dir, e.name)],
    );
}
const files = walk(base).filter(
  (p) =>
    !p.endsWith(".md") &&
    !p.endsWith("offline-manifest.js") &&
    !p.endsWith("sw.js") &&
    !p.endsWith("package.json"),
);
const heavy = files.filter((p) => p.includes("/engine/vendor/")),
  shell = files.filter((p) => !heavy.includes(p));
const hash = createHash("sha256");
hash.update("backgammon-offline-v2\0");
// Some browsers retain decoded stylesheets across service-worker upgrades.
// Give each HTML entry's local scripts/styles a new URL on every release.
const assetReference =
  /\b(src|href)="(?![a-z]+:|\/\/)([^"?#]+\.(?:css|m?js))(?:\?bgv=[a-z0-9]+)?"/g;
const htmlVersion = (text, version = "") =>
  text.replace(
    assetReference,
    (_, attr, path) => `${attr}="${path}${version ? `?bgv=${version}` : ""}"`,
  );
const workerPath = join(base, "sw.js");
const worker = readFileSync(workerPath, "utf8");
// Normalize the generated revision before hashing to avoid a circular hash.
// Updating the main worker bytes also fixes older registrations whose imported
// scripts can otherwise remain in Safari's HTTP cache until a later check.
const importLine = /importScripts\("\.\/offline-manifest\.js\?v=[a-z0-9]+"\);/;
if (!importLine.test(worker))
  throw new Error("Missing generated manifest import in sw.js");
hash.update(
  worker.replace(
    importLine,
    'importScripts("./offline-manifest.js?v=generated");',
  ),
);
for (const p of files.sort()) {
  const source = readFileSync(p);
  hash
    .update(relative(base, p))
    .update(p.endsWith(".html") ? htmlVersion(source.toString()) : source);
}
for (const shared of ["hub.css", "hub.js", "peer-room.js"]) {
  hash.update(shared).update(readFileSync(join(base, "..", "shared", shared)));
}
const url = (p) => "/backgammon/" + relative(base, p);
const engineDigests = Object.fromEntries(
  heavy.map((p) => [
    url(p),
    createHash("sha256").update(readFileSync(p)).digest("hex"),
  ]),
);
const version = hash.digest("hex").slice(0, 16);
for (const file of shell.filter((path) => path.endsWith(".html")))
  writeFileSync(file, htmlVersion(readFileSync(file, "utf8"), version));
writeFileSync(
  workerPath,
  worker.replace(
    importLine,
    `importScripts("./offline-manifest.js?v=${version}");`,
  ),
);
writeFileSync(
  join(base, "offline-manifest.js"),
  `// Generated by scripts/offline-manifest.mjs\nself.BG_CACHE_VERSION='${version}';\nself.BG_SHELL=${JSON.stringify([...shell.map(url), "/shared/hub.css", "/shared/hub.js", "/shared/peer-room.js"])};\nself.BG_ENGINE=${JSON.stringify(heavy.map(url))};\nself.BG_ENGINE_DIGESTS=${JSON.stringify(engineDigests)};\n`,
);
