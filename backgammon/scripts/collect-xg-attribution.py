#!/usr/bin/env python3
"""Recover per-move authors from the exact frozen reference HTML, without changing the study inputs."""
import hashlib
import json
import re
from pathlib import Path
from importlib.util import spec_from_file_location, module_from_spec
spec = spec_from_file_location('collector', Path(__file__).with_name('collect-xg-opening.py'))
collector = module_from_spec(spec)
spec.loader.exec_module(collector)
root = Path(__file__).resolve().parent.parent
raw = (root / 'docs/deep-book-xg-reference.json').read_bytes()
reference = json.loads(raw)
entries = {}
for source in reference['sources']:
    html = collector.fetch(source['url'].removeprefix(collector.BASE))
    if hashlib.sha256(html).hexdigest() != source['sha256']:
        raise ValueError('Frozen source HTML changed: ' + source['url'])
    chunks = re.split(r'<h2>(.*?)</h2>', html.decode('utf-8', errors='replace'), flags=re.S)
    positions = {}
    for i in range(1, len(chunks), 2):
        title = collector.plain(chunks[i]).split(' (')[0]
        body = collector.plain(chunks[i+1])
        notes = dict(re.findall(r'(\d+) Generated by (.*?)(?=\b\d+ Generated by|$)', body))
        credits = []
        for rank, footnote in re.findall(r'(\d+)\.\s+Book\s*(\d+)\s+', body):
            note = notes[footnote]
            match = re.match(r'(.+?) on (\d+/\d+/\d+) using (eXtreme Gammon \d+\.\d+)', note)
            if not match:
                raise ValueError('Unparsed author: ' + note)
            author, date, engine = match.groups()
            credits.append({'rank': int(rank), 'author': author.strip(), 'date': date, 'engine': engine.strip()})
        expected = next(p for p in source['positions'] if p['title'] == title)
        if [c['rank'] for c in credits] != [c['rank'] for c in expected['candidates']]:
            raise ValueError('Attribution mismatch: ' + title)
        positions[title] = credits
    entries[source['url']] = {'sha256': source['sha256'], 'positions': positions}
result = {'schema': 1, 'sourceSHA256': hashlib.sha256(raw).hexdigest(),
          'terms': 'https://www.extremegammon.com/GetOb.aspx', 'sources': entries}
(root / 'docs/xg-reference-attribution.json').write_text(json.dumps(result, indent=2) + '\n')
print('Attributed', sum(len(p) for s in entries.values() for p in s['positions'].values()), 'moves from hash-matched HTML')
