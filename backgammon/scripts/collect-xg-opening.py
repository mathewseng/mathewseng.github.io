#!/usr/bin/env python3
"""Fetch public XG opening/reply numeric references with source provenance.

Raw HTML stays in ignored test-results. This is comparison data, never an
input to GNUbg search or a replacement for its computed answers.
"""
import concurrent.futures
import hashlib
import json
import re
import sys
import urllib.request
from datetime import datetime, timezone
from html.parser import HTMLParser
from pathlib import Path

FAMILY = Path(__file__).resolve().parent.parent
BASE = 'https://www.extremegammon.com/'
CACHE = FAMILY / 'test-results/xg-opening-source'
CACHE.mkdir(parents=True, exist_ok=True)


class Text(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)


def plain(html):
    parser = Text()
    parser.feed(html)
    return ' '.join(' '.join(parser.parts).split())


def fetch(relative):
    file = CACHE / relative.split('/')[-1]
    if not file.exists():
        request = urllib.request.Request(BASE + relative, headers={'User-Agent': 'Backgammon EV research; public opening-book comparison'})
        with urllib.request.urlopen(request, timeout=60) as response:
            file.write_bytes(response.read())
    return file.read_bytes()


def parse_page(relative):
    raw = fetch(relative)
    html = raw.decode('utf-8', errors='replace')
    positions = []
    chunks = re.split(r'<h2>(.*?)</h2>', html, flags=re.S)
    for i in range(1, len(chunks), 2):
        title, body = plain(chunks[i]).split(' (')[0], plain(chunks[i+1])
        xgid = re.search(r'XGID=[-A-Oa-o]{26}(?::[-\d]+){9}', body)
        if not xgid:
            raise ValueError('Missing XGID: ' + title)
        pattern = r'(\d+)\.\s+Book\s*(\d+)\s+([\d/*() a-z]+?)\s+eq:\s*([+−-]\d+\.\d+)'
        matches = list(re.finditer(pattern, body))
        if not matches:
            raise ValueError('Missing candidates: ' + title)
        candidates = []
        for j, match in enumerate(matches):
            rank, footnote, move, equity = match.groups()
            tail = body[match.end():matches[j+1].start() if j+1 < len(matches) else len(body)]
            tail = re.split(r'\d+ Generated by', tail)[0]
            confidence = re.search(r'Conf\.:\s*±([\d.]+)', tail)
            outcomes = re.findall(r'([\d.]+)%\s*\(G:([\d.]+)%\s*B:([\d.]+)%\)', tail)
            method_match = re.search(r'\b' + footnote + r' Generated by (.*?)(?=\b\d+ Generated by|$)', body)
            method = method_match.group(1) if method_match else ''
            games = re.search(r'(\d+) Games rolled', method)
            policy = re.search(r'(Moves(?: and cube decisions)?:.*?)(?=\s+\d+ Generated|$)', method)
            candidates.append({
                'rank': int(rank), 'move': move.strip(), 'equity': float(equity.replace('−', '-')),
                'confidenceHalfWidth': float(confidence.group(1)) if confidence else None,
                'probabilities': [[float(x)/100 for x in row] for row in outcomes],
                'method': 'rollout' if games else 'XGRoller++' if 'XG Roller++' in method else 'unclassified',
                'trials': int(games.group(1)) if games else None,
                'policy': policy.group(1).strip() if policy else None,
            })
        if [c['rank'] for c in candidates] != list(range(1, len(candidates)+1)):
            raise ValueError('Incomplete candidate parse: ' + title)
        position = {'title': title, 'xgid': xgid.group(0), 'candidates': candidates}
        if title == 'Opening-65' and xgid.group(0) == 'XGID=-b----E-C---eF---c-e----A-:0:0:-1:32:0:0:3:0:10':
            position['normalizedXgid'] = 'XGID=-b----E-C---eE---c-e----B-:0:0:1:65:0:0:3:0:10'
            position['sourceIssue'] = 'Published diagram/XGID describes the reply 32 after 65R, while the heading and candidate table describe opening 65. Comparison reconstructs the standard opening from that heading; original XGID is preserved.'
        positions.append(position)
    expected = 15 if relative == 'OB/Opening_in_unlimited_game.html' else 21
    if len(positions) != expected:
        raise ValueError(f'{relative}: expected {expected}, got {len(positions)}')
    return {'url': BASE + relative, 'sha256': hashlib.sha256(raw).hexdigest(), 'positions': positions}


if __name__ == '__main__':
    index = fetch('Openingbook.aspx').decode('utf-8', errors='replace')
    links = ['OB/Opening_in_unlimited_game.html'] + list(dict.fromkeys(re.findall(r'href="(OB/Replies_to_[^"]+\.html)"', index)))
    if len(links) != 35:
        raise ValueError(f'Expected opening page and 34 reply pages; got {len(links)}')
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        sources = list(pool.map(parse_page, links))
    result = {'schema': 1, 'retrievedAt': datetime.now(timezone.utc).isoformat(),
              'sourceIndex': BASE + 'Openingbook.aspx',
              'context': {'matchLength': 0, 'jacoby': True, 'beavers': True, 'cube': 1, 'cubeOwner': None},
              'note': 'Published XG book 3.70; finite rollouts and XGRoller++ evaluations, not exact truth. Rules differ from the ordinary-cube GNU book by beavers.',
              'sources': sources}
    destination = Path(sys.argv[1]) if len(sys.argv) > 1 else FAMILY / 'docs/deep-book-xg-reference.json'
    destination.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps({'pages': len(sources), 'positions': sum(len(s['positions']) for s in sources), 'output': str(destination)}))
