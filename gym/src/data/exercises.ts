export const exercisesByCategory = exercises.reduce<
  Record<ExerciseCategory, ExerciseDefinition[]>
>(
  (groups, exercise) => {
    groups[exercise.category].push(exercise);
    return groups;
  },
  {
    chest: [],
    back: [],
    arms: [],
    shoulders: [],
    legs: [],
    carries: [],
    core: [],
  },
);

export const exerciseOptions = exercises.map(({ id, canonicalName }) => ({
  value: id,
  label: canonicalName,
}));
